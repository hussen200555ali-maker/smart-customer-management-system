-- ═══════════════════════════════════════════════════════════════════════
-- ملف تحسين الفهارس (Indexes Optimization)
-- الهدف: تحسين أداء الاستعلامات في قاعدة البيانات
-- ═══════════════════════════════════════════════════════════════════════

USE service_management;

-- ═══════════════════════════════════════════════════════════════════════
-- فهارس جديدة لتحسين الأداء
-- ═══════════════════════════════════════════════════════════════════════

-- ──────────────────────────────────────────────
-- فهارس الطلبات المركبة (للتنقية والترتيب)
-- ──────────────────────────────────────────────
-- تحسين استعلامات الفلترة حسب الحالة مع ترتيب التاريخ
CREATE INDEX idx_orders_status_created ON orders(status, created_at DESC);

-- تحسين استعلامات الإحصائيات (الحالة مكتملة + التاريخ)
CREATE INDEX idx_orders_status_date ON orders(status, created_at DESC);

-- ──────────────────────────────────────────────
-- فهارس تفاصيل الطلبات (لتحسين JOIN)
-- ──────────────────────────────────────────────
-- تحسين ربط details مع orders و services
CREATE INDEX idx_order_details_order_service ON order_details(order_id, service_id);

-- ──────────────────────────────────────────────
-- فهارس الخدمات (للبحث والترتيب)
-- ──────────────────────────────────────────────
-- تحسين البحث مع الفلترة حسب الفئة
CREATE INDEX idx_services_category_active ON services(category_id, is_active);

-- ──────────────────────────────────────────────
-- فهارس العملاء (للبحث)
-- ──────────────────────────────────────────────
-- تحسين البحث النصي في الأسماء
CREATE INDEX idx_customers_name ON customers(name(50));

-- ═══════════════════════════════════════════════════════════════════════
-- عرض الفهارس الموجودة
-- ═══════════════════════════════════════════════════════════════════════
SHOW INDEX FROM orders;
SHOW INDEX FROM order_details;
SHOW INDEX FROM services;
SHOW INDEX FROM customers;

